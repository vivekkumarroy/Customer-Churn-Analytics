def explain_customer(customer_id):

    # --------------------------------------------------------
    # 1. Check whether CustomerID exists
    # --------------------------------------------------------

    if customer_id not in customer_features.index:

        print(f"Customer {customer_id} not found.")

        return None


    # --------------------------------------------------------
    # 2. Get customer data
    # --------------------------------------------------------

    customer = customer_features.loc[customer_id]


    # --------------------------------------------------------
    # 3. Get model features
    # --------------------------------------------------------

    feature_names = list(X_train.columns)

    customer_input = customer[
        feature_names
    ].to_frame().T


    # --------------------------------------------------------
    # 4. Predict churn probability
    # --------------------------------------------------------

    churn_probability = final_model.predict_proba(
        customer_input
    )[0, 1]


    # --------------------------------------------------------
    # 5. Automatically selected threshold
    # --------------------------------------------------------

    threshold = best_threshold


    # --------------------------------------------------------
    # 6. Churn prediction
    # --------------------------------------------------------

    churn_prediction = int(
        churn_probability >= threshold
    )
    # --------------------------------------------------------
    #   Risk Level
    # --------------------------------------------------------
    risk = risk_level(churn_probability)


    # --------------------------------------------------------
    # 8. Explanation
    # --------------------------------------------------------

    explanations = []


    # ========================================================
    # LOGISTIC REGRESSION
    # ========================================================

    if best_model_name == 'Logistic Regression':

        # Get scaler
        scaler = final_model.named_steps['scaler']

        # Get LR model
        lr_model = final_model.named_steps['model']

        # Scale customer using SAME scaler
        customer_scaled = scaler.transform(
            customer_input
        )[0]

        # LR coefficients
        coefficients = lr_model.coef_[0]

        # Customer-specific contribution
        contributions = (
            customer_scaled * coefficients
        )

        for feature, value, contribution in zip(
            feature_names,
            customer_input.iloc[0],
            contributions
        ):

            if contribution > 0:

                effect = "Increases churn"

            else:

                effect = "Decreases churn"


            explanations.append({

                'Feature': feature,

                'Value': value,

                'Effect': effect,

                'Importance': abs(contribution)

            })


    # ========================================================
    # RANDOM FOREST
    # ========================================================

    elif best_model_name == 'Random Forest':

        import shap

        # SHAP explainer
        explainer = shap.TreeExplainer(
            final_model
        )

        shap_values = explainer.shap_values(
            customer_input
        )

        # Handle SHAP output
        if isinstance(shap_values, list):

            customer_shap = shap_values[1][0]

        else:

            customer_shap = shap_values[0]


        for feature, value, contribution in zip(
            feature_names,
            customer_input.iloc[0],
            customer_shap
        ):

            if contribution > 0:

                effect = "Increases churn"

            else:

                effect = "Decreases churn"


            explanations.append({

                'Feature': feature,

                'Value': value,

                'Effect': effect,

                'Importance': abs(contribution)

            })


    # ========================================================
    # XGBOOST
    # ========================================================

    elif best_model_name == 'XGBoost':

        import shap

        # SHAP explainer
        explainer = shap.TreeExplainer(
            final_model
        )

        shap_values = explainer(
            customer_input
        )

        customer_shap = shap_values.values[0]


        for feature, value, contribution in zip(
            feature_names,
            customer_input.iloc[0],
            customer_shap
        ):

            if contribution > 0:

                effect = "Increases churn"

            else:

                effect = "Decreases churn"


            explanations.append({

                'Feature': feature,

                'Value': value,

                'Effect': effect,

                'Importance': abs(contribution)

            })


    # --------------------------------------------------------
    # 9. Create explanation DataFrame
    # --------------------------------------------------------

    explanation_df = pd.DataFrame(
        explanations
    )


    explanation_df = explanation_df.sort_values(
        'Importance',
        ascending=False
    )


    # --------------------------------------------------------
    # 10. Print result
    # --------------------------------------------------------

    print("============================================")
    print("       CUSTOMER CHURN EXPLANATION")
    print("============================================")

    print(
        "Customer ID       :",
        customer_id
    )

    print(
        "Churn Probability :",
        round(churn_probability * 100, 2),
        "%"
    )

    print(
        "Prediction        :",
        "CHURN"
        if churn_prediction == 1
        else "NOT CHURN"
    )

    print(
        "Risk Level        :",
        risk
    )

    print(
        "Model             :",
        best_model_name
    )

    print(
        "Threshold         :",
        threshold
    )

    print("\n===== MAIN FACTORS =====")

    print(
        explanation_df.head(5)
    )


    # --------------------------------------------------------
    # 11. Return everything
    # --------------------------------------------------------

    return {

        'CustomerID': customer_id,

        'ChurnProbability': churn_probability,

        'ChurnPrediction': churn_prediction,

        'RiskLevel': risk,

        'Model': best_model_name,

        'Threshold': threshold,

        'Explanation': explanation_df

    }
