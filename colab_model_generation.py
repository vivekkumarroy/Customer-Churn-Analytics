def assign_risk_value_segment(row):

    if (
        row['ValueLevel'] == 'High Value'
        and
        row['RiskLevel'] in ['HIGH', 'MEDIUM']
    ):
        return 'Priority Retain'

    # High-value customers with low churn risk
    elif (
        row['ValueLevel'] == 'High Value'
        and
        row['RiskLevel'] == 'LOW'
    ):
        return 'VIP Loyal'

    # Low-value customers with high/medium churn risk
    elif (
        row['ValueLevel'] == 'Low Value'
        and
        row['RiskLevel'] in ['HIGH', 'MEDIUM']
    ):
        return 'Automated Campaign'

    # Low-value + low-risk
    else:
        return 'Normal Marketing'


