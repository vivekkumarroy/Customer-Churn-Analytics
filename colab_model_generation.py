# 1. import
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GridSearchCV, StratifiedKFold, train_test_split,cross_val_predict
from sklearn.metrics import ( accuracy_score,precision_score,recall_score,f1_score,roc_auc_score,confusion_matrix)

# ============================================================
# 2. PIPELINE
# ============================================================

log_reg_pipeline = Pipeline([

    ('scaler', StandardScaler()),

    ('model', LogisticRegression(
        max_iter=1000,
        random_state=42
    ))
])


# ============================================================
# 3. PARAMETER GRID
# ============================================================

param_grid_lr = {
    'model__C': [0.01, 0.1, 1, 10],
    'model__class_weight': [None, 'balanced']
}


# ============================================================
# 4. 5-FOLD CROSS VALIDATION
# ============================================================

cv_strategy = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)


# ============================================================
# 5. GRID SEARCH
# ============================================================

lr_model = GridSearchCV(
    estimator=log_reg_pipeline,
    param_grid=param_grid_lr,
    cv=cv_strategy,
    scoring='f1',
    n_jobs=-1
)


# ============================================================
# 6. TRAIN
# ============================================================

lr_model.fit(X_train, y_train)


print("===== LOGISTIC REGRESSION TRAINING =====")

print("Best CV F1:",
      lr_model.best_score_)

print("Best Parameters:",
      lr_model.best_params_)


# ============================================================
# 7. OUT-OF-FOLD PROBABILITIES
# ============================================================
# IMPORTANT:
# We use X_train here, NOT X_test.
#
# These probabilities are used to select the threshold.
# This prevents us from using the test set to choose
# the threshold.

lr_prob_cv = cross_val_predict(
    lr_model.best_estimator_,
    X_train,
    y_train,
    cv=cv_strategy,
    method='predict_proba',
    n_jobs=-1
)[:, 1]


# ============================================================
# 8. THRESHOLD TUNING
# ============================================================

threshold_results = []

for threshold in [0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60]:

    y_pred_cv = (
        lr_prob_cv >= threshold
    ).astype(int)

    precision = precision_score(
        y_train,
        y_pred_cv
    )

    recall = recall_score(
        y_train,
        y_pred_cv
    )

    f1 = f1_score(
        y_train,
        y_pred_cv
    )

    threshold_results.append({
        'Threshold': threshold,
        'Precision': precision,
        'Recall': recall,
        'F1': f1
    })


threshold_results = pd.DataFrame(
    threshold_results
)


print("\n===== THRESHOLD RESULTS =====")

print(threshold_results)


# ============================================================
# 9. SELECT BEST THRESHOLD
# ============================================================
# Business requirement:
# Recall should be at least 80%.
#
# Among thresholds with Recall >= 80%,
# select the one with the highest F1.

valid_thresholds = threshold_results[
    threshold_results['Recall'] >= 0.80
]


if len(valid_thresholds) > 0:

    best_threshold = valid_thresholds.loc[
        valid_thresholds['F1'].idxmax(),
        'Threshold'
    ]

else:

    best_threshold = threshold_results.loc[
        threshold_results['F1'].idxmax(),
        'Threshold'
    ]


print("\n===== BEST THRESHOLD =====")

print("Best Threshold:",
      best_threshold)


# ============================================================
# 10. FINAL TEST PROBABILITY
# ============================================================
# IMPORTANT:
# X_test is used ONLY now for final evaluation.

lr_prob_test = lr_model.predict_proba(
    X_test
)[:, 1]


# ============================================================
# 11. FINAL TEST PREDICTION
# ============================================================

lr_pred_test = (
    lr_prob_test >= best_threshold
).astype(int)


# ============================================================
# 12. FINAL TEST RESULTS
# ============================================================

print("\n===== FINAL TEST RESULTS =====")

